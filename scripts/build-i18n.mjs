// Builds the localized landing pages, account page strings, and sitemap from
// i18n/index.template.html and i18n/locales/<locale>.json. Run: npm run i18n
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE_URL = "https://syntheticinsights.net/";

// Matches the Smartodo app's supported locales. The first entry is served at the site root.
const LOCALES = [
  { code: "en", hreflang: "en" },
  { code: "de", hreflang: "de" },
  { code: "es", hreflang: "es" },
  { code: "fr", hreflang: "fr" },
  { code: "id", hreflang: "id" },
  { code: "it", hreflang: "it" },
  { code: "ja", hreflang: "ja" },
  { code: "ko", hreflang: "ko" },
  { code: "pt", hreflang: "pt" },
  { code: "ru", hreflang: "ru" },
  { code: "tr", hreflang: "tr" },
  { code: "zh-hans", hreflang: "zh-Hans" },
  { code: "zh-hant", hreflang: "zh-Hant" },
];
const DEFAULT_LOCALE = LOCALES[0];
const PLURAL_CATEGORIES = new Set(["zero", "one", "two", "few", "many", "other"]);
const GENERATED_NOTE =
  "<!-- Generated by scripts/build-i18n.mjs from i18n/index.template.html and i18n/locales. Edit those, then run: npm run i18n -->";

const folderOf = (locale) => (locale === DEFAULT_LOCALE ? "" : `${locale.code}/`);
const urlOf = (locale) => `${SITE_URL}${folderOf(locale)}`;

const isPlural = (value) =>
  value !== null &&
  typeof value === "object" &&
  !Array.isArray(value) &&
  "other" in value &&
  Object.keys(value).every((key) => PLURAL_CATEGORIES.has(key));

// Every locale must have exactly the keys of the default locale; plural forms must
// cover each category the language uses.
const checkShape = (reference, value, htmlLang, path) => {
  if (isPlural(reference)) {
    if (!isPlural(value)) throw new Error(`${path}: expected plural forms`);
    for (const category of new Intl.PluralRules(htmlLang).resolvedOptions().pluralCategories) {
      if (!(category in value)) throw new Error(`${path}: missing plural form "${category}"`);
    }
    return;
  }
  if (typeof reference === "string") {
    if (typeof value !== "string" || !value.trim()) throw new Error(`${path}: expected text`);
    return;
  }
  if (Array.isArray(reference)) {
    if (!Array.isArray(value) || value.length !== reference.length) {
      throw new Error(`${path}: expected ${reference.length} items`);
    }
    reference.forEach((item, index) => checkShape(item, value[index], htmlLang, `${path}[${index}]`));
    return;
  }
  const extra = Object.keys(value).filter((key) => !(key in reference));
  if (extra.length) throw new Error(`${path}: unexpected keys ${extra.join(", ")}`);
  for (const key of Object.keys(reference)) {
    if (!(key in value)) throw new Error(`${path}.${key}: missing`);
    checkShape(reference[key], value[key], htmlLang, `${path}.${key}`);
  }
};

const inlineJson = (value) => JSON.stringify(value).replace(/</g, "\\u003c");

const lookup = (data, path) => {
  const value = path.split(".").reduce((node, key) => node?.[key], data);
  if (typeof value !== "string") throw new Error(`Template placeholder {{${path}}} has no text`);
  return value;
};

const render = (template, data) => template.replace(/\{\{([\w.]+)\}\}/g, (_, path) => lookup(data, path));

const renderPage = (template, locale, text) => {
  const base = locale === DEFAULT_LOCALE ? "" : "../";
  const alternates = [
    ...LOCALES.map(
      (other) => `    <link rel="alternate" hreflang="${other.hreflang}" href="${urlOf(other)}" />`,
    ),
    `    <link rel="alternate" hreflang="x-default" href="${urlOf(DEFAULT_LOCALE)}" />`,
  ].join("\n");
  const ogLocaleAlternates = LOCALES.filter((other) => other !== locale)
    .map((other) => `    <meta property="og:locale:alternate" content="${other.text.meta.ogLocale}" />`)
    .join("\n");
  const languageLinks = LOCALES.map((other) => {
    const href = `${base}${folderOf(other)}` || "./";
    const current = other === locale ? ' aria-current="page"' : "";
    return `              <li><a href="${href}" hreflang="${other.hreflang}" lang="${other.text.meta.htmlLang}" data-locale="${other.code}"${current}>${other.text.meta.name}</a></li>`;
  }).join("\n");
  const jsonLd = {
    "@context": "https://schema.org",
    "@type": "SoftwareApplication",
    name: "Smartodo",
    alternateName: ["Smart To Do", "Smart Todo"],
    sameAs: [
      "https://apps.apple.com/app/id6755520449",
      "https://play.google.com/store/apps/details?id=net.syntheticinsights.smartodo",
    ],
    applicationCategory: "ProductivityApplication",
    operatingSystem: "macOS, iOS, Android, Windows, Linux",
    description: text.page.ldDescription,
    inLanguage: locale.hreflang,
    url: urlOf(locale),
    image: `${SITE_URL}assets/img/share/smartodo-${locale.code}.png`,
    offers: { "@type": "Offer", price: "0", priceCurrency: "USD" },
    featureList: text.page.ldFeatures,
    author: { "@type": "Organization", name: "Synthetic Insights", url: SITE_URL },
  };
  const html = render(template, {
    ...text,
    locale: locale.code,
    base,
    url: urlOf(locale),
    alternates,
    ogLocaleAlternates,
    languageLinks,
    langQuery: locale === DEFAULT_LOCALE ? "" : `?lang=${locale.code}`,
    cards: inlineJson(text.cards),
    jsonLd: inlineJson(jsonLd),
  });
  return html.replace("<!DOCTYPE html>\n", `<!DOCTYPE html>\n${GENERATED_NOTE}\n`);
};

const renderAccountText = () => {
  const byLocale = Object.fromEntries(
    LOCALES.map((locale) => [locale.code, { htmlLang: locale.text.meta.htmlLang, ...locale.text.account }]),
  );
  return [
    "// Generated by scripts/build-i18n.mjs from i18n/locales. Edit those, then run: npm run i18n",
    `const ACCOUNT_TEXT = ${JSON.stringify(byLocale, null, 2)};`,
    "",
  ].join("\n");
};

const renderSitemap = () => {
  const today = new Date().toISOString().slice(0, 10);
  const links = LOCALES.map(
    (locale) => `    <xhtml:link rel="alternate" hreflang="${locale.hreflang}" href="${urlOf(locale)}" />`,
  )
    .concat(`    <xhtml:link rel="alternate" hreflang="x-default" href="${urlOf(DEFAULT_LOCALE)}" />`)
    .join("\n");
  const pages = LOCALES.map(
    (locale) => `  <url>
    <loc>${urlOf(locale)}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>weekly</changefreq>
    <priority>1.0</priority>
${links}
  </url>`,
  ).join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${pages}
  <url>
    <loc>${SITE_URL}privacy.html</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.5</priority>
  </url>
</urlset>
`;
};

for (const locale of LOCALES) {
  locale.text = JSON.parse(await readFile(join(ROOT, "i18n/locales", `${locale.code}.json`), "utf8"));
}
for (const locale of LOCALES) {
  checkShape(DEFAULT_LOCALE.text, locale.text, locale.text.meta.htmlLang, locale.code);
}

const template = await readFile(join(ROOT, "i18n/index.template.html"), "utf8");
for (const locale of LOCALES) {
  const folder = join(ROOT, folderOf(locale));
  await mkdir(folder, { recursive: true });
  await writeFile(join(folder, "index.html"), renderPage(template, locale, locale.text));
}
await writeFile(join(ROOT, "assets/js/account_text.js"), renderAccountText());
await writeFile(join(ROOT, "sitemap.xml"), renderSitemap());
console.log(`Built ${LOCALES.length} locales: ${LOCALES.map((locale) => locale.code).join(", ")}`);
